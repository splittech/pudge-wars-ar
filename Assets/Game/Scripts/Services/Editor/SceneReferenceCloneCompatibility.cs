using System;
using System.IO;
using System.Reflection;
using System.Runtime.CompilerServices;
using UnityEditor;
using UnityEngine;

namespace Game.Services.Editor
{
    [InitializeOnLoad]
    internal static class SceneReferenceCloneCompatibility
    {
        static SceneReferenceCloneCompatibility()
        {
            var project = Directory.GetParent(Application.dataPath);
            if (project?.Parent?.Name != "VP" || project.Parent.Parent?.Name != "Library")
                return;

            // SceneReference 5.0.0 refreshes the read-only clone AssetDatabase on play.
            // Keep the maps generated by the main editor; detach only that trigger.
            foreach (Assembly assembly in AppDomain.CurrentDomain.GetAssemblies())
            {
                Type listener = assembly.GetType(
                    "Eflatun.SceneReference.Editor.MapGeneratorTriggers.PlayModeListener");
                if (listener == null)
                    continue;

                RuntimeHelpers.RunClassConstructor(listener.TypeHandle);
                MethodInfo method = listener.GetMethod("EditorApplication_OnPlayModeStateChanged",
                    BindingFlags.Static | BindingFlags.NonPublic);
                if (method == null)
                {
                    Debug.LogWarning("SceneReference clone compatibility: play-mode trigger API changed.");
                    return;
                }

                var handler = (Action<PlayModeStateChange>)Delegate.CreateDelegate(
                    typeof(Action<PlayModeStateChange>), method);
                EditorApplication.playModeStateChanged -= handler;
                return;
            }
        }
    }
}
